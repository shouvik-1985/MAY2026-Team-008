def test_openapi_schema_is_reachable_and_substantial(client):
    response = client.get("/openapi.json")
    assert response.status_code in (200, 201)
    schema = response.json()
    assert "paths" in schema
    assert len(schema["paths"]) > 20


def test_openapi_schema_covers_every_implemented_api_route(client):
    schema = client.get("/openapi.json").json()
    documented_paths = set(schema["paths"].keys())
    missing = sorted(
        {
            route.path
            for route in app.routes
            if getattr(route, "path", "").startswith("/api/")
            and getattr(route, "include_in_schema", True)
            and route.path not in documented_paths
        }
    )
    assert not missing, f"implemented but undocumented in the OpenAPI schema: {missing}"


