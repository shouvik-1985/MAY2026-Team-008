"""Probe-based contract tests.

Everything else in this suite tests specific, hand-picked business logic: "given
this input, this endpoint returns that output." These tests are different in
kind -- they walk the *live* FastAPI route table and OpenAPI schema and probe
general contract properties that should hold for the API as a whole:

  - every route that depends on get_current_user actually enforces it (rejecting
    a request with no token at all with a client-auth status, 401 or 403)
  - error responses have a consistent shape across the whole app
  - the OpenAPI schema stays in sync with what's actually implemented
  - unknown routes/methods fail cleanly instead of leaking a stack trace
  - GET endpoints are side-effect-free (calling twice gives the same answer)
  - responses never leak password hashes
  - "list" endpoints keep a consistent envelope shape

Because the auth/method-not-allowed probes are generated by walking the app's
own OpenAPI schema at import time, a newly added endpoint is automatically
covered -- nobody has to remember to write a one-off test for it. That
introspection is wrapped defensively (see `_ROUTE_INTROSPECTION_ERROR` below):
if it ever breaks, the probes report zero cases instead of crashing
collection, and `test_route_introspection_actually_ran` catches that with a
clear message rather than a silent false-negative "all green."
"""
import re

import pytest

from app.main import app

PATH_PARAM_STUB = "1"


def _stub_path(path: str) -> str:
    """Replace every {param} placeholder with a harmless stub value. "1" is a
    valid int (most of our path params) and an equally valid string (item
    keys, certificate keys, etc.), so it works generically either way."""
    return re.sub(r"\{[^}]+\}", PATH_PARAM_STUB, path)


def _discover_protected_routes():
    """Return (method, concrete_path) for every route whose OpenAPI operation
    declares a security requirement -- i.e. every route that's supposed to
    require a logged-in user.

    This walks the *public* OpenAPI schema (via app.openapi(), the exact dict
    FastAPI serves at /openapi.json) rather than FastAPI's internal Dependant
    tree. FastAPI adds an operation to `security` whenever a SecurityBase
    dependency (here, the OAuth2PasswordBearer used by get_current_user)
    appears anywhere in that route's dependency tree -- this is documented,
    stable, public behavior, not an internal implementation detail. It's also
    immune to a class of bug that hit an earlier version of this file: an
    identity/name check on the dependency callable can silently find nothing
    if the test runner's rootdir/sys.path setup ever causes `app` to get
    imported under two different module paths (easy to trigger by nesting
    test files a few directories deep, as this repo's tests/probe_testing/
    layout does) -- the OpenAPI schema has no such object-identity concept.
    """
    discovered = []
    schema = app.openapi()
    for path, operations in schema.get("paths", {}).items():
        for method, operation in operations.items():
            if method.upper() not in {"GET", "POST", "PUT", "PATCH", "DELETE"}:
                continue
            if operation.get("security"):
                discovered.append((method.upper(), _stub_path(path)))
    return discovered


try:
    PROTECTED_ROUTES = _discover_protected_routes()
    _ROUTE_INTROSPECTION_ERROR = None
except Exception as exc:  # pragma: no cover - defensive, see module docstring
    PROTECTED_ROUTES = []
    _ROUTE_INTROSPECTION_ERROR = exc


def test_route_introspection_actually_ran():
    """Guards the two probes below against silently covering zero routes.
    We have far more than 20 auth-protected endpoints, so a low count means
    the introspection broke, not that the API shrank."""
    assert _ROUTE_INTROSPECTION_ERROR is None, f"route introspection failed: {_ROUTE_INTROSPECTION_ERROR!r}"
    assert len(PROTECTED_ROUTES) > 20, (
        f"only found {len(PROTECTED_ROUTES)} auth-protected routes -- introspection likely broke"
    )


@pytest.mark.parametrize("method,path", PROTECTED_ROUTES, ids=[f"{m} {p}" for m, p in PROTECTED_ROUTES])
def test_protected_route_rejects_missing_auth(client, method, path):
    response = client.request(method, path)
    assert response.status_code in (401, 403), (
        f"{method} {path} returned {response.status_code}, not an auth failure, with no token"
    )


