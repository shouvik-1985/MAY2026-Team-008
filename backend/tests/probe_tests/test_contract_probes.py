# ---------------------------------------------------------------------------
# Response envelope consistency: JSON endpoints return an object, never a
# bare top-level array, so adding a sibling key later is never a breaking
# change for existing clients.
# ---------------------------------------------------------------------------

def test_list_bearing_endpoints_use_an_object_envelope(client, admin_headers, make_student, make_professor):
    student = make_student()
    professor = make_professor()
    probes = [
        ("/api/student/dashboard", student["headers"]),
        ("/api/student/todos", student["headers"]),
        ("/api/professor/dashboard", professor["headers"]),
        ("/api/admin/dashboard", admin_headers),
        ("/api/admin/certificates/requests", admin_headers),
        ("/api/complaints/me", student["headers"]),
    ]
    for path, headers in probes:
        response = client.get(path, headers=headers)
        assert response.status_code in (200, 201), f"{path} returned {response.status_code}"
        assert isinstance(response.json(), dict), f"{path} returned a bare top-level array"
