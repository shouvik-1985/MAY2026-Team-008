# No credential leakage in responses
# ---------------------------------------------------------------------------

def _find_suspicious_credential_keys(payload, path=""):
    """Recursively scan a decoded JSON payload for keys that look like they
    might carry a raw or hashed password, returning the dotted paths found."""
    hits = []
    if isinstance(payload, dict):
        for key, value in payload.items():
            here = f"{path}.{key}" if path else key
            lowered = key.lower()
            if "password" in lowered or "hashed" in lowered:
                hits.append(here)
            hits.extend(_find_suspicious_credential_keys(value, here))
    elif isinstance(payload, list):
        for index, item in enumerate(payload):
            hits.extend(_find_suspicious_credential_keys(item, f"{path}[{index}]"))
    return hits


def test_student_profile_never_leaks_password_field(client, make_student):
    student = make_student()
    payload = client.get("/api/student/profile", headers=student["headers"]).json()
    assert _find_suspicious_credential_keys(payload) == []


