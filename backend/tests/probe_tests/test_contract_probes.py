def test_error_responses_share_a_consistent_shape(client, admin_headers, make_student):
    student = make_student()
    probes = [
        client.get("/api/admin/dashboard", headers=student["headers"]),  # 403
        client.get("/api/resources/9999999/file"),  # 404
        client.delete("/api/admin/users/9999999", headers=admin_headers),  # 404
        client.post("/api/student/todos", json={"title": ""}, headers=student["headers"]),  # 422
    ]
    for response in probes:
        assert response.status_code >= 400, response.text
        body = response.json()
        assert "detail" in body, f"{response.status_code} response has no 'detail' key: {body}"


